export function translateLegacyText(source: string): string {
  const trimmed = source.trim();
  if (!trimmed) return source;
  const translated = exact[trimmed];
  if (translated) return source.replace(trimmed, translated);
  let result = source;
  for (const [from, to] of fragments) result = result.split(from).join(to);
  return result;
}
